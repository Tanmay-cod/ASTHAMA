export function buildSeedPredictionsForPatient(pkg: PatientSeedPackage): Prediction[] {
  return pkg.historySeed.map((item, idx) => {
    const symp: SymptomLog = {
      id: `seed_symp_${pkg.patient.id}_${idx}`,
      user_id: pkg.patient.user_id,
      cough: item.symptoms.cough,
      wheezing: item.symptoms.wheeze,
      shortness_of_breath: item.symptoms.shortness,
      chest_tightness: item.symptoms.chest,
      night_cough: item.symptoms.night,
      symptom_score: item.symptoms.cough + item.symptoms.wheeze + item.symptoms.shortness + item.symptoms.chest + item.symptoms.night,
      recorded_at: daysAgo(item.days, item.hours),
    };

    const sens: SensorReading = {
      id: `seed_sens_${pkg.patient.id}_${idx}`,
      user_id: pkg.patient.user_id,
      spo2: item.spo2,
      heart_rate: item.hr,
      temperature_c: item.temp,
      humidity_pct: item.hum,
      dust_density_mgm3: Math.round((item.pm25 / (1000 * 0.6)) * 1000) / 1000,
      pm25_est: item.pm25,
      aqi: item.aqi,
      pefr_lmin: item.pefr,
      source: 'esp32_wifi',
      recorded_at: daysAgo(item.days, item.hours),
    };

    const pred = runAsthmaRiskInference(pkg.patient, symp, sens);
    pred.id = `seed_pred_${pkg.patient.id}_${idx}`;
    pred.created_at = daysAgo(item.days, item.hours);
    return pred;
  });
}
